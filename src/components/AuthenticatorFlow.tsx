"use client";

import { useState } from "react";
import { resendSecondFactor, verifySecondFactor, type AuthenticationStep, type TwoFactorChallenge, type TwoFactorResult, type User } from "@/auth";
import { TwoFactor } from "./TwoFactor";
import styles from "./TwoFactor.module.css";

export function AuthenticatorFlow({ initial, onComplete, onCancel }: {
  initial: AuthenticationStep;
  onComplete: (user: User) => void;
  onCancel: () => void;
}) {
  const [step, setStep] = useState(initial);
  const [code, setCode] = useState("");
  const [recovery, setRecovery] = useState(false);
  const [saved, setSaved] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");

  const accept = (next: AuthenticationStep) => {
    setCode("");
    if ("user" in next && !next.recovery_codes?.length) onComplete(next.user);
    else setStep(next);
  };

  if ("user" in step) return <RecoveryCodes result={step} saved={saved} onSaved={setSaved} onContinue={() => onComplete(step.user)} />;
  const challenge: TwoFactorChallenge = step;
  if (challenge.method === "email_enrollment" || !challenge.method) return <>
    <p className="ic-hint">Verify your registered email once to set up your authenticator. Future sign-ins will use your authenticator app.</p>
    <TwoFactor key={challenge.challenge_id} challenge={challenge} onVerify={async (id, value) => accept(await verifySecondFactor(id, value))} onResend={resendSecondFactor} onCancel={onCancel} />
  </>;

  const setup = challenge.method === "totp_setup";
  return <section className={styles.flow} aria-label="Authenticator verification">
    <h2>{setup ? "Set up your authenticator" : "Verify your sign-in"}</h2>
    {setup ? <>
      <p>In an authenticator app such as Microsoft Authenticator or Google Authenticator, add an account and scan this QR code.</p>
      {/* The QR is generated by our backend; sending it to an image service would expose the setup secret. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={challenge.qr_code} alt="Scan with your authenticator app" width={240} height={240} style={{ background: "white", maxWidth: "100%", height: "auto" }} />
      <details><summary>Can’t scan? Enter the setup key manually</summary><p className="ic-hint">Account: Invoice Checker. Time-based codes, six digits, changing every 30 seconds.</p><code style={{ overflowWrap: "anywhere", userSelect: "all" }}>{challenge.secret}</code></details>
      <p>Enter the six-digit code from your app to finish setup. Keep this QR code and setup key private.</p>
    </> : <p>{recovery ? "Enter one of the recovery codes you saved during setup. Each recovery code works once." : "Enter the current six-digit code from your authenticator app."}</p>}
    <form className={styles.flow} onSubmit={async event => {
      event.preventDefault(); setBusy(true); setError("");
      try { accept(await verifySecondFactor(challenge.challenge_id, code.trim())); }
      catch (reason) { setError(reason instanceof Error ? reason.message : "Could not verify that code."); }
      finally { setBusy(false); }
    }}>
      <label className="ic-field">{recovery ? "Recovery code" : "Authenticator code"}<input className="ic-input" type="text" inputMode={recovery ? "text" : "numeric"} autoComplete="one-time-code" required minLength={recovery ? 20 : 6} maxLength={recovery ? 32 : 6} pattern={recovery ? undefined : "[0-9]{6}"} value={code} onChange={event => setCode(event.target.value)} /></label>
      {error ? <p role="alert" className="ic-hint ic-hint--error">{error}</p> : null}
      <button className="ic-btn ic-btn--primary" disabled={busy}>{busy ? "Verifying…" : setup ? "Enable authenticator" : "Verify code"}</button>
      {!setup ? <button className="ic-link" type="button" disabled={busy} onClick={() => { setRecovery(!recovery); setCode(""); setError(""); }}>{recovery ? "Use authenticator app" : "Use a recovery code"}</button> : null}
      <button className="ic-link" type="button" disabled={busy} onClick={onCancel}>Back to sign in</button>
      <p className="ic-hint">This sign-in step expires after five minutes. If you lose your authenticator and recovery codes, contact the server operator. Email password resets do not remove 2FA.</p>
    </form>
  </section>;
}

function RecoveryCodes({ result, saved, onSaved, onContinue }: { result: TwoFactorResult; saved: boolean; onSaved: (value: boolean) => void; onContinue: () => void }) {
  return <section className={styles.flow} aria-label="Save recovery codes">
    <h2>Save your recovery codes</h2>
    <p>Store these in a safe place, such as your password manager. Each replaces one authenticator code if you lose your phone. They are shown only once.</p>
    <pre style={{ whiteSpace: "pre-wrap", userSelect: "all" }}>{result.recovery_codes?.join("\n")}</pre>
    <label><input type="checkbox" checked={saved} onChange={event => onSaved(event.target.checked)} /> I have saved my recovery codes</label>
    <button className="ic-btn ic-btn--primary" disabled={!saved} onClick={onContinue}>Continue to my workspace</button>
  </section>;
}
